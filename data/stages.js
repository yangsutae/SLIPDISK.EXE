// 레벨 목차: 단계와 그 단계에 들어가는 레벨 id를 순서대로 적는다. 이 순서가 스테이지 선택의 탭·칸 순서이자 해금 순서다.
// 레벨 내용은 data/levels/<id>.js에 레벨 하나씩 있다. 게임은 이 목차에 적힌 id의 파일만 불러온다.
//
// 레벨 추가
//   1. data/levels/의 레벨 파일 하나를 복사해 <id>.js로 저장하고 내용을 고친다. 파일 이름과 id가 같아야 한다.
//        defineLevel({ id, name, ko, map })
//        id    '단계-번호' 문자열 (예: '5-1'). 저장 기록을 id로 찾으므로 한 번 내보낸 레벨의 id는 바꾸지 않는다.
//        name  게임에 나오는 영문 이름. 대문자·숫자·공백과 . , : ! ? - + / ' ( ) 만 쓰고 10자 안으로 짓는다.
//        ko    원래 이름. 문서와 맞춰 보는 용도이고 게임에는 나오지 않는다.
//        map   길이가 같은 문자열 배열. 외곽 # 테두리 없이 쓴다(화면의 외곽 벽이 정지 경계).
//              .  빈칸   #  벽   P  컴퓨터(정확히 1개)   o  파일   C  백신   M  바이러스
//   2. 아래 STAGES의 알맞은 단계 levels에 id를 넣는다. 새 단계는 { no, name, ko, levels } 한 줄을 더한다.
//        no    탭에 STAGE n으로 나오는 번호     name  영문 단계 이름(10자 안)     ko  원래 이름
//   3. 이 폴더에서 `node tools/check-levels.js`로 형식, 이름, 목차와 파일이 맞는지, 해법을 확인한다.
